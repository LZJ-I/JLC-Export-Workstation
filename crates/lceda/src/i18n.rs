use std::env;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    Zh,
    En,
}

impl Lang {
    pub fn from_code(code: &str) -> Self {
        if code.to_ascii_lowercase().starts_with("zh") {
            Self::Zh
        } else {
            Self::En
        }
    }

    pub fn as_code(self) -> &'static str {
        match self {
            Self::Zh => "zh",
            Self::En => "en",
        }
    }

    pub fn detect() -> Self {
        for key in ["LCEDA_LANG", "LANG", "LC_ALL", "LC_MESSAGES"] {
            if let Ok(v) = env::var(key) {
                if !v.is_empty() {
                    return Self::from_code(&v);
                }
            }
        }
        #[cfg(windows)]
        if let Some(lang) = windows_ui_lang() {
            return lang;
        }
        Self::En
    }

    #[allow(dead_code)]
    pub fn toggle(self) -> Self {
        match self {
            Self::Zh => Self::En,
            Self::En => Self::Zh,
        }
    }
}

#[cfg(windows)]
fn windows_ui_lang() -> Option<Lang> {
    #[link(name = "kernel32")]
    extern "system" {
        fn GetUserDefaultUILanguage() -> u16;
    }
    // PRIMARYLANGID; LANG_CHINESE == 0x04
    let primary = unsafe { GetUserDefaultUILanguage() } & 0x3ff;
    Some(if primary == 0x04 { Lang::Zh } else { Lang::En })
}

